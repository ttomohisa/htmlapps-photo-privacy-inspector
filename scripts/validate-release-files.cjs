'use strict';
// Validate the exact standalone artifacts prior to creating a GitHub Release.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {gunzipSync}=require('node:zlib');
const root=path.resolve(__dirname,'..');
const config=JSON.parse(fs.readFileSync(path.join(root,'app.config.json'),'utf8'));
assert.match(config.version,/^[0-9]+\.[0-9]+\.[0-9]+$/,'Stable SemVer release required');
const standalone=fs.readFileSync(path.join(root,'dist/index.html'));
const html=standalone.toString('utf8');
assert.match(html,/<meta http-equiv="Content-Security-Policy"/);
assert.ok(html.includes("connect-src 'none'"),'Standalone must block network requests');
const inlineConfig=html.match(/<script type="application\/json" id="app-config">([\s\S]*?)<\/script>/);
assert.ok(inlineConfig,'Missing embedded configuration');
assert.equal(JSON.parse(inlineConfig[1]).version,config.version,'Embedded app version must match');
const inlineManifest=html.match(/<script type="application\/json" id="build-manifest">([\s\S]*?)<\/script>/);
assert.ok(inlineManifest,'Missing build manifest');
assert.equal(JSON.parse(inlineManifest[1]).app.version,config.version,'Build manifest version must match');
const selfExtract=fs.readFileSync(path.join(root,'dist/index.self-extract.html'),'utf8');
assert.ok(selfExtract.includes("connect-src 'none'"),'Self-extract must block network requests');
const payload=selfExtract.match(/<script id="self-extract-payload" type="application\/octet-stream">([\s\S]*?)<\/script>/);
assert.ok(payload,'Missing self-extract payload');
const restored=gunzipSync(Buffer.from(payload[1].trim(),'base64'));
assert.deepEqual(restored,standalone,'Self-extract must reproduce the release HTML byte-for-byte');
const expectedDigest=selfExtract.match(/<meta name="self-extract-source-sha256" content="([a-f0-9]{64})"/)?.[1];
assert.equal(expectedDigest,crypto.createHash('sha256').update(standalone).digest('hex'));
for(const file of ['dependency-manifest.json','self-extract-manifest.json'])assert.ok(fs.statSync(path.join(root,'dist',file)).size>0,file+' missing');
console.log('PASS release artifacts: version, CSP, manifests, SHA-256 and self-extract payload verified ('+config.version+')');
